const KNOWN_FRONTEND_URL = 'https://ecf-platform-frontend-50801509587.us-central1.run.app';

function esClavePlaceholder(val) {
  const v = String(val || '').trim();
  return (
    !v ||
    v === 'COLOCAR_LA_CLAVE_LOCALMENTE' ||
    v === 'ecf_live_clave_ficticia_ejemplo_no_real' ||
    v.startsWith('ecf_sim_') ||
    v.includes('FICTICIA') ||
    v.includes('EJEMPLO')
  );
}

function normalizarBaseUrlImecf(urlInput) {
  const rawUrl = String(urlInput || DEFAULT_BASE_URL)
    .trim()
    .replace(/\/+$/, '');
  if (!rawUrl || rawUrl.includes('ecf-platform-frontend-50801509587.us-central1.run.app')) {
    return DEFAULT_BASE_URL;
  }
  return rawUrl;
}

/**
 * Obtiene la configuración actual de IMECF desde variables de entorno privadas.
 * Prioriza `IMECF_API_KEY` en `.env` según lo indicado por el profesor, con soporte compatible para `ECF_API_KEY`.
 * Si en `.env` se colocó la URL de la plataforma web (frontend), la normaliza automáticamente a la base real de la API.
 */
function obtenerConfiguracion() {
  const rawUrl = (process.env.IMECF_API_BASE_URL || process.env.ECF_API_BASE_URL || DEFAULT_BASE_URL)
    .trim()
    .replace(/\/+$/, '');

  const baseUrl = normalizarBaseUrlImecf(rawUrl);
  const urlNormalizadaDesdeFrontend = rawUrl.includes('ecf-platform-frontend-50801509587.us-central1.run.app');

  const rawImecfKey = (process.env.IMECF_API_KEY || '').trim();
  const rawEcfKey = (process.env.ECF_API_KEY || '').trim();

  const apiKey = !esClavePlaceholder(rawImecfKey)
    ? rawImecfKey
    : (!esClavePlaceholder(rawEcfKey) ? rawEcfKey : '');

  const nombreVariableKey = !esClavePlaceholder(rawImecfKey)
    ? 'IMECF_API_KEY'
    : (!esClavePlaceholder(rawEcfKey) ? 'ECF_API_KEY' : 'IMECF_API_KEY');

  const timeoutMs = parseInt(process.env.ECF_REQUEST_TIMEOUT_MS, 10) || DEFAULT_TIMEOUT_MS;
  const defaultIndicador = ['1', '2', '3', '4'].includes(String(process.env.ECF_DEFAULT_INDICADOR_FACTURACION || '').trim())
    ? String(process.env.ECF_DEFAULT_INDICADOR_FACTURACION).trim()
    : '4';

  const tieneApiKeyReal = !esClavePlaceholder(apiKey);
  const allowProduction =
    String(process.env.IMECF_ALLOW_PRODUCTION || 'false').trim().toLowerCase() === 'true' ||
    String(process.env.IMECF_ALLOW_PRODUCTION || '') === '1';

  return {
    frontendPlatformUrl: KNOWN_FRONTEND_URL,
    baseUrl,
    rawConfiguredUrl: rawUrl,
    urlNormalizadaDesdeFrontend,
    apiKey,
    nombreVariableKey,
    tieneApiKeyReal,
    // El flujo real NUNCA cae silenciosamente en simulación cuando falta la API Key
    modoSimulacion: false,
    allowProduction,
    ambienteConfigurado: process.env.ECF_AMBIENTE || 'TesteCF',
    timeoutMs,
    defaultIndicador,
  };
}

/**
 * Configuración segura para enviar a las vistas (EJS): NUNCA incluye la API Key.
 * Expone `tieneApiKey`, que es el nombre que usan las plantillas.
 */
function obtenerConfiguracionPublica() {
  const { apiKey, nombreVariableKey, rawConfiguredUrl, ...resto } = obtenerConfiguracion();
  return { ...resto, tieneApiKey: resto.tieneApiKeyReal };
}

/**
 * Sanitiza cualquier texto de error o log para garantizar que NUNCA se exponga IMECF_API_KEY ni ECF_API_KEY
 */
function sanitizarTextoSeguridad(texto) {
  if (!texto) return '';
  let limpio = String(texto);
  const k1 = (process.env.IMECF_API_KEY || '').trim();
  const k2 = (process.env.ECF_API_KEY || '').trim();
  if (k1 && k1.length >= 4) {
    limpio = limpio.split(k1).join('[IMECF_API_KEY_OCULTA]');
  }
  if (k2 && k2.length >= 4) {
    limpio = limpio.split(k2).join('[IMECF_API_KEY_OCULTA]');
  }
  limpio = limpio.replace(/ecf_(live|test)_[a-zA-Z0-9_-]+/gi, '[IMECF_API_KEY_OCULTA]');
  return limpio;
}

/**
 * Error tipado para la integración de IMECF
 */
class ImecfError extends Error {
  constructor(message, { tipo = 'ERROR_GENERAL', statusCode = 400, detalle = null, incierto = false } = {}) {
    super(sanitizarTextoSeguridad(message));
    this.name = 'ImecfError';
    this.tipo = tipo;
    this.statusCode = statusCode;
    this.detalle = detalle ? sanitizarTextoSeguridad(JSON.stringify(detalle)) : null;
    this.incierto = Boolean(incierto);
  }
}

/**
 * Normaliza un RNC o Cédula eliminando guiones y espacios
 */
function normalizarRncCedula(valor) {
  if (!valor) return '';
  return String(valor).replace(/\D/g, '');
}

/**
 * Formatea un número a string con 2 decimales exactos ("1500.00")
 */
function formatearDecimal(valor) {
  const num = Number(valor);
  if (!Number.isFinite(num)) return '0.00';
  return (Math.round((num + Number.EPSILON) * 100) / 100).toFixed(2);
}

/**
 * Redondea un número a 2 decimales como Number
 */
function redondear2(valor) {
  const num = Number(valor);
  if (!Number.isFinite(num)) return 0;
  return Math.round((num + Number.EPSILON) * 100) / 100;
}

/**
 * Formatea una fecha a dd-mm-YYYY según requerimiento de DGII para FechaLimitePago
 */
function formatearFechaDgii(fechaInput) {
  const fecha = fechaInput ? new Date(fechaInput) : new Date(Date.now() + 30 * 24 * 60 * 60 * 1000);
  if (Number.isNaN(fecha.getTime())) {
    const fallback = new Date(Date.now() + 30 * 24 * 60 * 60 * 1000);
    const dd = String(fallback.getDate()).padStart(2, '0');
    const mm = String(fallback.getMonth() + 1).padStart(2, '0');
    const yyyy = fallback.getFullYear();
    return `${dd}-${mm}-${yyyy}`;
  }
  const dd = String(fecha.getDate()).padStart(2, '0');
  const mm = String(fecha.getMonth() + 1).padStart(2, '0');
  const yyyy = fecha.getFullYear();
  return `${dd}-${mm}-${yyyy}`;
}

/**
 * Verifica que el payload de e-CF NO contenga campos autogenerados ni datos clínicos sensibles
 */
function verificarPrivacidadYEstructura(payload, datosClinicosProhibidos = []) {
  if (!payload || typeof payload !== 'object' || !payload.ECF) {
    throw new ImecfError('El cuerpo del comprobante debe contener el objeto raíz "ECF".', {
      tipo: 'ERROR_VALIDACION',
      statusCode: 400,
    });
  }

  const encabezado = payload.ECF.Encabezado || {};
  const idDoc = encabezado.IdDoc || {};

  // 1. Verificar que NO se envíen campos autogenerados por IMECF
  if ('eNCF' in idDoc || 'FechaVencimientoSecuencia' in idDoc) {
    throw new ImecfError(
      'No se deben enviar eNCF ni FechaVencimientoSecuencia; la plataforma IMECF los genera automáticamente.',
      { tipo: 'ERROR_VALIDACION', statusCode: 400 }
    );
  }
  if ('Emisor' in encabezado || 'FechaHoraFirma' in payload.ECF) {
    throw new ImecfError(
      'No se deben enviar Emisor ni FechaHoraFirma; la plataforma IMECF los inyecta automáticamente.',
      { tipo: 'ERROR_VALIDACION', statusCode: 400 }
    );
  }

  // 2. Verificar que no existan propiedades ni textos de historia clínica / diagnóstico médico
  const jsonSerializado = JSON.stringify(payload);
  const clavesProhibidas = [
    'diagnostico_clinico',
    'hallazgos_clinicos',
    'motivo_consulta',
    'tratamiento_plan',
    'signos_vitales',
    'antecedentes_revisados',
    'antecedentes_personales',
    'antecedentes_alergicos',
    'notas_adicionales',
  ];

  for (const clave of clavesProhibidas) {
    if (jsonSerializado.includes(`"${clave}"`)) {
      throw new ImecfError(
        `Privacidad médica: el campo clínico "${clave}" no puede incluirse en un comprobante fiscal.`,
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
  }

  for (const textoClinico of datosClinicosProhibidos) {
    const limpio = String(textoClinico || '').trim();
    if (limpio.length >= 10 && jsonSerializado.toLowerCase().includes(limpio.toLowerCase())) {
      throw new ImecfError(
        'Privacidad médica: se detectó información clínica o diagnóstico en la descripción fiscal del comprobante.',
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
  }

  return true;
}

/**
 * Construye y valida en el servidor el JSON requerido por IMECF a partir de la consulta/factura guardada.
 *
 * @param {Object} consulta - Registro de la consulta médica con datos del paciente, servicio y ARS
 * @param {Object} opciones - Opciones seleccionadas por el usuario autorizado
 * @returns {Object} { payload, resumenFiscal, esquemaAplicado }
 */
function construirPayloadEcf(consulta, opciones = {}) {
  if (!consulta || !consulta.id) {
    throw new ImecfError('No se encontró la factura/consulta de origen para construir el comprobante.', {
      tipo: 'ERROR_VALIDACION',
      statusCode: 400,
    });
  }

  const config = obtenerConfiguracion();
  const tipoEcf = String(opciones.tipoEcf || 'E32').trim().toUpperCase();
  const esquema = ESQUEMAS_DOCUMENTADOS[tipoEcf];

  if (!esquema) {
    throw new ImecfError(`Tipo de comprobante "${tipoEcf}" inválido. Debe elegir E31 (Crédito Fiscal) o E32 (Consumo).`, {
      tipo: 'ERROR_VALIDACION',
      statusCode: 400,
    });
  }

  // Tratamiento fiscal configurable (por opción explícita -> por servicio en BD -> por variable de entorno -> '4' Exento)
  const indicadorFacturacion = String(
    opciones.indicadorFacturacion || consulta.servicio_indicador_facturacion || config.defaultIndicador || '4'
  ).trim();

  const configImpuesto = INDICADORES_FACTURACION[indicadorFacturacion];
  if (!configImpuesto) {
    throw new ImecfError(
      `Indicador de facturación "${indicadorFacturacion}" no válido. Valores permitidos: 4 (Exento), 1 (18%), 2 (16%), 3 (0%).`,
      { tipo: 'ERROR_VALIDACION', statusCode: 400 }
    );
  }

  // Determinación y validación del importe base en el servidor a partir de la factura guardada
  const valorTotalGuardado = redondear2(consulta.valor_total);
  const diferenciaPacienteGuardada = redondear2(consulta.diferencia_paciente);
  const valorCubiertoArs = redondear2(consulta.valor_cubierto_ars);

  const criterioMonto = String(opciones.criterioMonto || 'TOTAL').trim().toUpperCase();
  let precioUnitarioBase = valorTotalGuardado;

  if (criterioMonto === 'COPAGO') {
    if (diferenciaPacienteGuardada <= 0) {
      throw new ImecfError(
        'El copago del paciente es RD$ 0.00. Seleccione facturar el "Valor Total del Servicio" o verifique la liquidación.',
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
    precioUnitarioBase = diferenciaPacienteGuardada;
  } else if (criterioMonto === 'TOTAL') {
    precioUnitarioBase = valorTotalGuardado;
  } else {
    throw new ImecfError('El criterio de monto a facturar no es válido (use TOTAL o COPAGO).', {
      tipo: 'ERROR_VALIDACION',
      statusCode: 400,
    });
  }

  if (!Number.isFinite(precioUnitarioBase) || precioUnitarioBase <= 0) {
    throw new ImecfError(
      'El monto a facturar debe ser mayor a RD$ 0.00. No se pueden emitir comprobantes electrónicos con importe cero o negativo.',
      { tipo: 'ERROR_VALIDACION', statusCode: 400 }
    );
  }

  const cantidadItem = 1;
  const montoItem = redondear2(cantidadItem * precioUnitarioBase);

  // Cálculo de impuestos según IndicadorFacturacion
  let montoGravadoTotal = 0;
  let montoExento = 0;
  let totalItbis = 0;

  if (configImpuesto.esExento) {
    montoExento = montoItem;
  } else {
    montoGravadoTotal = montoItem;
    totalItbis = redondear2(montoItem * (configImpuesto.tasaItbis / 100));
  }

  const montoTotal = redondear2(montoGravadoTotal + montoExento + totalItbis);

  // Validación cruzada de cuadre aritmético en el servidor
  if (redondear2(montoGravadoTotal + montoExento + totalItbis) !== montoTotal) {
    throw new ImecfError('Error de validación aritmética en los totales del comprobante electrónico.', {
      tipo: 'ERROR_VALIDACION',
      statusCode: 400,
    });
  }

  // Validación de datos fiscales del comprador según reglas de E31 y E32
  const rncInput =
    opciones.rncComprador !== undefined && opciones.rncComprador !== null
      ? opciones.rncComprador
      : consulta.paciente_identificacion || '';
  const rncComprador = normalizarRncCedula(rncInput);

  const nombrePacienteCompleto = [consulta.paciente_nombre, consulta.paciente_apellido]
    .filter(Boolean)
    .join(' ')
    .trim();
  const razonSocialComprador = String(
    opciones.razonSocialComprador !== undefined && opciones.razonSocialComprador !== null && String(opciones.razonSocialComprador).trim() !== ''
      ? opciones.razonSocialComprador
      : nombrePacienteCompleto
  )
    .trim()
    .slice(0, 150);

  const correoComprador = String(opciones.correoComprador || consulta.paciente_correo || '').trim();

  if (tipoEcf === 'E31') {
    if (!rncComprador || ![9, 11].includes(rncComprador.length)) {
      throw new ImecfError(
        'Para emitir una Factura de Crédito Fiscal (E31) es obligatorio un RNC (9 dígitos) o Cédula (11 dígitos) válido del comprador.',
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
    if (!razonSocialComprador || razonSocialComprador.length < 2) {
      throw new ImecfError(
        'Para emitir una Factura de Crédito Fiscal (E31) es obligatorio indicar la Razón Social o Nombre del comprador.',
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
  } else if (tipoEcf === 'E32') {
    if (montoTotal >= 250000) {
      if (!rncComprador || ![9, 11].includes(rncComprador.length)) {
        throw new ImecfError(
          'En Facturas de Consumo (E32) con monto igual o superior a RD$ 250,000.00 es obligatorio el RNC (9 dígitos) o Cédula (11 dígitos) del comprador.',
          { tipo: 'ERROR_VALIDACION', statusCode: 400 }
        );
      }
      if (!razonSocialComprador || razonSocialComprador.length < 2) {
        throw new ImecfError(
          'En Facturas de Consumo (E32) con monto igual o superior a RD$ 250,000.00 es obligatorio el nombre o razón social del comprador.',
          { tipo: 'ERROR_VALIDACION', statusCode: 400 }
        );
      }
    } else if (rncComprador && ![9, 11].includes(rncComprador.length)) {
      throw new ImecfError(
        'El RNC o Cédula del comprador debe contener exactamente 9 dígitos (RNC) u 11 dígitos (Cédula), o dejarse vacío si es consumo menor a RD$ 250,000.',
        { tipo: 'ERROR_VALIDACION', statusCode: 400 }
      );
    }
  }

  // Tipo de pago y forma de pago
  const tipoPago = ['1', '2', '3'].includes(String(opciones.tipoPago || '1')) ? String(opciones.tipoPago) : '1';
  const formaPagoNum = [1, 2, 3, 4].includes( parseInt(opciones.formaPago, 10) )
    ? parseInt(opciones.formaPago, 10)
    : (tipoPago === '2' ? 4 : 1);

  // Descripción estrictamente fiscal del servicio (NUNCA datos clínicos)
  const nombreServicioBase = String(consulta.servicio_nombre || 'Consulta Médica General')
    .replace(/[\r\n\t]+/g, ' ')
    .trim();
  const sufijoCriterio = criterioMonto === 'COPAGO' && valorCubiertoArs > 0 ? ' (Copago Paciente)' : '';
  const nombreItemFiscal = `${nombreServicioBase}${sufijoCriterio}`.slice(0, 80);

  // Construcción de IdDoc según esquema documentado de IMECF
  const idDoc = {
    TipoeCF: esquema.tipoeCF,
    IndicadorEnvioDiferido: '1',
    IndicadorMontoGravado: '0',
    TipoIngresos: '01',
    TipoPago: tipoPago,
    TablaFormasPago: {
      FormaDePago: [
        {
          FormaPago: formaPagoNum,
          MontoPago: formatearDecimal(montoTotal),
        },
      ],
    },
  };

  if (tipoPago === '2') {
    idDoc.FechaLimitePago = formatearFechaDgii(opciones.fechaLimitePago);
  }

  // Construcción de Comprador
  let compradorObj = null;
  if (tipoEcf === 'E31' || rncComprador || razonSocialComprador) {
    compradorObj = {};
    if (rncComprador) {
      compradorObj.RNCComprador = rncComprador;
    }
    if (razonSocialComprador) {
      compradorObj.RazonSocialComprador = razonSocialComprador;
    }
    if (tipoEcf === 'E31' && correoComprador && correoComprador.includes('@')) {
      compradorObj.CorreoComprador = correoComprador;
    }
  }

  // Construcción de Totales según IndicadorFacturacion
  const totalesObj = {
    MontoGravadoTotal: formatearDecimal(montoGravadoTotal),
    MontoExento: formatearDecimal(montoExento),
    TotalITBIS: formatearDecimal(totalItbis),
    MontoTotal: formatearDecimal(montoTotal),
    MontoNoFacturable: '0',
  };

  if (!configImpuesto.esExento) {
    totalesObj[configImpuesto.campoMonto] = formatearDecimal(montoGravadoTotal);
    totalesObj[configImpuesto.campoTasa] = String(configImpuesto.tasaItbis);
    totalesObj[configImpuesto.campoTotalItbis] = formatearDecimal(totalItbis);
  }

  // Construcción de DetallesItems.Item
  const itemObj = {
    NumeroLinea: '1',
    IndicadorFacturacion: indicadorFacturacion,
    NombreItem: nombreItemFiscal,
    IndicadorBienoServicio: '2', // 2 = Servicio médico
    CantidadItem: String(cantidadItem),
    UnidadMedida: '43',
    PrecioUnitarioItem: formatearDecimal(precioUnitarioBase),
    MontoItem: formatearDecimal(montoItem),
  };

  const encabezado = {
    Version: '1.0',
    IdDoc: idDoc,
  };

  if (compradorObj && Object.keys(compradorObj).length > 0) {
    encabezado.Comprador = compradorObj;
  }

  encabezado.Totales = totalesObj;

  const payload = {
    ECF: {
      Encabezado: encabezado,
      DetallesItems: {
        Item: itemObj,
      },
    },
  };

  // Verificación de privacidad médica y ausencia de campos autogenerados
  verificarPrivacidadYEstructura(payload, [
    consulta.diagnostico_clinico,
    consulta.hallazgos_clinicos,
    consulta.tratamiento_plan,
    consulta.antecedentes_revisados,
    consulta.notas_adicionales,
  ]);

  return {
    payload,
    esquemaAplicado: esquema,
    resumenFiscal: {
      tipoEcf,
      tipoeCF: esquema.tipoeCF,
      indicadorFacturacion,
      descripcionImpuesto: configImpuesto.nombre,
      tasaItbis: configImpuesto.tasaItbis,
      criterioMonto,
      tipoPago,
      formaPago: formaPagoNum,
      rncComprador: rncComprador || null,
      razonSocialComprador: razonSocialComprador || null,
      correoComprador: correoComprador || null,
      nombreItem: nombreItemFiscal,
      precioUnitario: redondear2(precioUnitarioBase),
      montoGravadoTotal: redondear2(montoGravadoTotal),
      montoExento: redondear2(montoExento),
      totalItbis: redondear2(totalItbis),
      montoTotal: redondear2(montoTotal),
    },
  };
}

/**
 * Extrae el arreglo de pasos reportados por IMECF en `responseJson`:
 * - AUTENTICACION_EXITOSA
 * - DOCUMENTO_FIRMADO
 * - RESPUESTA_DGII
 * - TRACK_STATUS
 * - ERROR
 */
function extraerPasosRespuestaImecf(responseJson) {
  let parsed = responseJson;
  if (typeof parsed === 'string') {
    try {
      parsed = JSON.parse(parsed);
    } catch (_) {
      return [];
    }
  }
  if (Array.isArray(parsed)) {
    return parsed;
  }
  if (parsed && Array.isArray(parsed.responseJson)) {
    return parsed.responseJson;
  }
  if (parsed && parsed.data && Array.isArray(parsed.data.responseJson)) {
    return parsed.data.responseJson;
  }
  return [];
}

/**
 * Extrae mensajes o errores detallados desde la estructura real devuelta por IMECF.
 */
function extraerMensajesDgiiDesdeImecf(doc) {
  if (!doc || typeof doc !== 'object') return [];
  const mensajes = [];
  if (Array.isArray(doc.mensajes)) {
    for (const m of doc.mensajes) {
      mensajes.push({
        codigo: m.codigo ?? null,
        valor: sanitizarTextoSeguridad(m.valor || m.mensaje || JSON.stringify(m)),
      });
    }
  }
  const pasos = extraerPasosRespuestaImecf(doc.responseJson);
  for (const paso of pasos) {
    if (paso?.status === 'ERROR' && paso?.data?.error) {
      mensajes.push({
        codigo: paso.status,
        valor: sanitizarTextoSeguridad(paso.data.error),
      });
    } else if (paso?.data?.mensajes && Array.isArray(paso.data.mensajes)) {
      for (const m of paso.data.mensajes) {
        mensajes.push({
          codigo: m.codigo ?? paso.status,
          valor: sanitizarTextoSeguridad(m.valor || m.mensaje || JSON.stringify(m)),
        });
      }
    } else if (paso?.data?.error && paso.data.error !== null) {
      mensajes.push({
        codigo: paso.status || 'DGII',
        valor: sanitizarTextoSeguridad(
          typeof paso.data.error === 'string' ? paso.data.error : JSON.stringify(paso.data.error)
        ),
      });
    }
  }
  if (mensajes.length === 0 && doc.errorMessage) {
    mensajes.push({
      codigo: null,
      valor: sanitizarTextoSeguridad(doc.errorMessage),
    });
  }
  return mensajes;
}

/**
 * Ejecuta una petición HTTP hacia el backend de IMECF con manejo de autenticación, timeout y errores
 */
async function ejecutarPeticionImecf(ruta, { method = 'GET', body = null, timeoutMs = null, accept = 'application/json' } = {}) {
  const config = obtenerConfiguracion();

  if (!config.tieneApiKeyReal) {
    throw new ImecfError(
      'Falta configurar la clave real en IMECF_API_KEY dentro del archivo .env. Solicite o coloque la API Key proporcionada por el profesor antes de emitir o consultar comprobantes en IMECF.',
      { tipo: 'ERROR_CONFIGURACION', statusCode: 503 }
    );
  }

  const url = `${config.baseUrl}${ruta}`;
  const ms = timeoutMs || config.timeoutMs;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), ms);

  const headers = {
    'X-API-Key': config.apiKey,
    Accept: accept,
  };

  if (body !== null) {
    headers['Content-Type'] = 'application/json';
  }

  try {
    const response = await fetch(url, {
      method,
      headers,
      body: body !== null ? JSON.stringify(body) : undefined,
      signal: controller.signal,
    });
    clearTimeout(timer);

    const contentType = response.headers.get('content-type') || '';

    if (accept === 'application/xml' && response.ok && (contentType.includes('xml') || contentType.includes('text'))) {
      const xmlText = await response.text();
      return { ok: true, status: response.status, xml: xmlText };
    }

    let parsed = null;
    const rawText = await response.text();
    try {
      parsed = rawText ? JSON.parse(rawText) : {};
    } catch (_) {
      parsed = { message: rawText };
    }

    if (!response.ok) {
      const rawMsg = parsed?.message || parsed?.error || `Error HTTP ${response.status} desde la plataforma IMECF.`;
      const msgServidor = sanitizarTextoSeguridad(
        Array.isArray(rawMsg) ? rawMsg.join('; ') : String(rawMsg)
      );

      if (response.status === 401 || response.status === 403) {
        throw new ImecfError(
          `Error de autenticación o permisos con IMECF (${response.status}): Verifique que IMECF_API_KEY en .env sea válida, esté activa y tenga permisos de emisión/lectura.`,
          { tipo: 'ERROR_AUTENTICACION', statusCode: response.status, detalle: parsed }
        );
      }

      if (
        response.status === 400 &&
        /certificado|secuencia|firma|configuraci[oó]n|vencid/i.test(msgServidor)
      ) {
        throw new ImecfError(
          `Requisito pendiente en la plataforma IMECF: ${msgServidor}. Verifique en la cuenta de IMECF (Configuración > Empresa) que el certificado digital (.p12) y las secuencias fiscales estén activas en ambiente TesteCF.`,
          { tipo: 'ERROR_CONFIGURACION', statusCode: 400, detalle: parsed }
        );
      }

      if (response.status === 400 || response.status === 422) {
        throw new ImecfError(`Validación rechazada por IMECF: ${msgServidor}`, {
          tipo: 'ERROR_VALIDACION',
          statusCode: 400,
          detalle: parsed,
        });
      }

      if (response.status === 404) {
        throw new ImecfError(`Comprobante no encontrado en la plataforma IMECF (${msgServidor}).`, {
          tipo: 'ERROR_NO_ENCONTRADO',
          statusCode: 404,
          detalle: parsed,
        });
      }

      throw new ImecfError(`Error en la plataforma IMECF (${response.status}): ${msgServidor}`, {
        tipo: 'ERROR_COMUNICACION',
        statusCode: response.status >= 500 ? 502 : response.status,
        detalle: parsed,
      });
    }

    return { ok: true, status: response.status, data: parsed };
  } catch (err) {
    clearTimeout(timer);
    if (err instanceof ImecfError) {
      throw err;
    }

    if (err.name === 'AbortError' || /timeout|aborted/i.test(err.message || '')) {
      throw new ImecfError(
        `Tiempo de espera agotado (${ms} ms) al comunicarse con IMECF. El estado del envío es INCIERTO; debe conciliarse antes de reenviar para evitar duplicados.`,
        {
          tipo: 'ERROR_TIMEOUT',
          statusCode: 504,
          incierto: true,
        }
      );
    }

    throw new ImecfError(
      `Error de comunicación de red con IMECF: ${sanitizarTextoSeguridad(err.message || 'No se pudo conectar al servidor remoto')}.`,
      {
        tipo: 'ERROR_COMUNICACION',
        statusCode: 502,
        incierto: method === 'POST',
      }
    );
  }
}

/**
 * Verifica la conectividad con IMECF y comprueba a qué ambiente (`TesteCF`, `CerteCF` o `eCF` Producción)
 * corresponde la API Key del profesor mediante `GET /api/v1/ecf?limit=5`.
 * Impide realizar emisiones en producción (`eCF`) durante pruebas a menos que `IMECF_ALLOW_PRODUCTION=true`.
 */
async function verificarConexionYAmbienteImecf() {
  const config = obtenerConfiguracion();

  if (!config.tieneApiKeyReal) {
    return {
      ok: false,
      configurado: false,
      baseUrl: config.baseUrl,
      frontendPlatformUrl: config.frontendPlatformUrl,
      ambienteDetectado: null,
      esProduccion: false,
      bloqueadoPorProduccion: false,
      mensaje: 'Falta configurar IMECF_API_KEY en el archivo .env del servidor.',
    };
  }

  try {
    const res = await ejecutarPeticionImecf('/api/v1/ecf?limit=5', { method: 'GET', timeoutMs: 12000 });
    const body = res.data || {};
    const items = Array.isArray(body)
      ? body
      : Array.isArray(body.data)
      ? body.data
      : Array.isArray(body.items)
      ? body.items
      : [];

    const primero = items.length > 0 ? items[0] : null;
    const ambienteDetectado = primero?.ambiente || body.ambiente || null;
    const esProduccion = ambienteDetectado === 'eCF';
    const bloqueadoPorProduccion = esProduccion && !config.allowProduction;

    return {
      ok: true,
      configurado: true,
      baseUrl: config.baseUrl,
      frontendPlatformUrl: config.frontendPlatformUrl,
      ambienteDetectado,
      esProduccion,
      bloqueadoPorProduccion,
      totalComprobantesPrevios: body.total ?? items.length,
      ultimoEncf: primero?.encf || null,
      ultimoEstado: primero?.estado || null,
      mensaje: ambienteDetectado
        ? `Conexión autenticada con IMECF exitosa. Ambiente detectado en la cuenta: ${ambienteDetectado}${esProduccion ? ' (PRODUCCIÓN)' : ' (PRUEBAS / CERTIFICACIÓN)'}.`
        : 'Conexión autenticada con IMECF exitosa (X-API-Key válida). Aún no existen comprobantes previos en la cuenta para leer el campo ambiente.',
    };
  } catch (err) {
    return {
      ok: false,
      configurado: true,
      baseUrl: config.baseUrl,
      frontendPlatformUrl: config.frontendPlatformUrl,
      ambienteDetectado: null,
      esProduccion: false,
      bloqueadoPorProduccion: false,
      tipoError: err.tipo || 'ERROR_COMUNICACION',
      statusCode: err.statusCode || 502,
      mensaje: sanitizarTextoSeguridad(err.message),
    };
  }
}

/**
 * Envía el comprobante electrónico a IMECF mediante POST /api/v1/ecf/send.
 *
 * Reglas estrictas:
 * - NO genera identificadores con prefijos `sim-` ni `trk-sim-`.
 * - NO inventa RNC del emisor, certificados ni estados `Aceptado`.
 * - Antes de emitir, verifica qué ambiente corresponde a `IMECF_API_KEY` y bloquea si es `eCF` (Producción)
 *   cuando `IMECF_ALLOW_PRODUCTION` es `false`.
 */
async function enviarComprobante(payload, resumenFiscal, { consultaId, forzarSimulacion = false, simularTimeout = false } = {}) {
  const config = obtenerConfiguracion();

  if (forzarSimulacion) {
    throw new ImecfError(
      'El envío real solo se realiza mediante la API de IMECF (POST /api/v1/ecf/send).',
      { tipo: 'ERROR_VALIDACION', statusCode: 400 }
    );
  }

  if (!config.tieneApiKeyReal) {
    throw new ImecfError(
      'No se puede emitir el comprobante porque falta configurar IMECF_API_KEY en el archivo .env. Coloque la API Key proporcionada por el profesor antes de emitir.',
      { tipo: 'ERROR_CONFIGURACION', statusCode: 503 }
    );
  }

  // Soporte para probar el manejo de timeout incierto de forma controlada
  if (simularTimeout) {
    throw new ImecfError(
      'Tiempo de espera agotado durante el envío a IMECF. El resultado se ha marcado como INCIERTO_TIMEOUT para conciliación previa antes de permitir un reenvío.',
      {
        tipo: 'ERROR_TIMEOUT',
        statusCode: 504,
        incierto: true,
      }
    );
  }

  // 1. Verificar el ambiente asociado a la clave del profesor antes de hacer una emisión real
  const verificacion = await verificarConexionYAmbienteImecf();
  if (!verificacion.ok) {
    throw new ImecfError(
      `No se pudo verificar la cuenta en IMECF antes de emitir: ${verificacion.mensaje}`,
      {
        tipo: verificacion.tipoError || 'ERROR_COMUNICACION',
        statusCode: verificacion.statusCode || 502,
        incierto: false,
      }
    );
  }

  if (verificacion.bloqueadoPorProduccion) {
    throw new ImecfError(
      'La clave IMECF_API_KEY configurada corresponde al ambiente de PRODUCCIÓN (eCF) de la DGII, pero IMECF_ALLOW_PRODUCTION está en false. Por seguridad se bloqueó el envío para no emitir comprobantes fiscales reales durante las pruebas.',
      {
        tipo: 'ERROR_CONFIGURACION',
        statusCode: 403,
        incierto: false,
      }
    );
  }

  // 2. Envío real a POST /api/v1/ecf/send
  const resultado = await ejecutarPeticionImecf('/api/v1/ecf/send', {
    method: 'POST',
    body: payload,
  });

  const bodyResp = resultado.data || {};
  const doc = bodyResp.data || bodyResp;

  if (!doc || (!doc.id && !doc._id && !doc.encf && !doc.eNCF)) {
    throw new ImecfError(
      'La respuesta de IMECF no incluyó un identificador de comprobante (id / encf). No se marcó el comprobante como enviado.',
      {
        tipo: 'ERROR_COMUNICACION',
        statusCode: 502,
        detalle: bodyResp,
      }
    );
  }

  const mensajesExtraidos = extraerMensajesDgiiDesdeImecf(doc);
  const errorDetalle = doc.errorMessage
    ? sanitizarTextoSeguridad(doc.errorMessage)
    : mensajesExtraidos.length > 0 && ['Rechazado', 'ERROR_AL_ENVIAR_A_DGII'].includes(doc.estado)
    ? mensajesExtraidos.map((m) => m.valor).join(' | ')
    : null;

  return {
    modoSimulacion: false,
    ecfIdExterno: doc.id || doc._id || null,
    encf: doc.encf || doc.eNCF || null,
    tipoEcf: doc.tipoEcf ? (String(doc.tipoEcf).startsWith('E') ? doc.tipoEcf : `E${doc.tipoEcf}`) : resumenFiscal.tipoEcf,
    estado: doc.estado || 'PENDIENTE_ENVIO_AL_SERVICIO_DGII',
    dgiiCodigoEstado: doc.codigoEstado !== undefined ? String(doc.codigoEstado) : null,
    dgiiMensajes: mensajesExtraidos,
    fechaRecepcionDgii: doc.fechaRecepcion || null,
    trackId: doc.trackId || null,
    codigoSeguridad: doc.codigoSeguridad || null,
    dgiiUrl: doc.dgiiUrl || null,
    xmlUrl: doc.xmlUrl || null,
    ambiente: doc.ambiente || verificacion.ambienteDetectado || null,
    secuenciaUtilizada: Boolean(doc.secuenciaUtilizada),
    enviadoDgii: Boolean(doc.enviado),
    mensajeError: errorDetalle,
    xmlFirmado: null,
    requestJsonImecf: doc.requestJson || null,
    responsePayload: bodyResp,
  };
}

